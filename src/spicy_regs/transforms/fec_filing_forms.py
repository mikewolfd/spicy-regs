def map_filing_text(row, selection, *, header_row, read_body, mapping=None, layout=None):
    """Keep narrative text and exact field/body pointers without financial meaning.

    The caller supplies ``read_body(reference)`` using the maintained source
    ``filing_body`` reader and verified original or derived member storage. A
    missing/refused body raises; it is never substituted with empty text. Source
    syntax belongs to that reader. The caller retains original-to-member pins.
    Standalone text has no positional dictionary; TEXT records require an exact
    reviewed mapping and layout. Native back references remain unresolved.
    """
    table = "fec_filing_text_observations"
    native = json.loads(row["metadata_json"])
    bodies = native.get("embedded_bodies", [])
    kind = native.get("kind")
    result: dict
    if kind == "record":
        if mapping not in filing_text_mappings() or layout is None:
            raise ValueError("TEXT requires its explicitly reviewed narrative mapping and layout")
        typed, evidence = map_filing_financial(row, selection, mapping, layout=layout, header_row=header_row)
        result = {n: typed.get(n) for n in COMMON_TEXT + EXTRA_TEXT + _TEXT_IDENTIFIERS + ["source_cycle"]}
        result["native_fields"] = _native_fields(native, layout)
        position = int(next(p for n, p in mapping.fields.text if n == "native_text"))
        if len(bodies) > 1 or any(b.get("field_index") != position for b in bodies):
            raise ValueError("Narrative body differs from the defined TEXT position")
        pointer = f"/fields/{position}"
        text = native["fields"].get(str(position))
        status = "source_missing" if position >= native["field_count"] else "native_field"
        if bodies and str(position) in native["fields"]:
            raise ValueError("Narrative position cannot contain both a field and a body reference")
    elif kind == "text":
        if mapping is not None or layout is not None:
            raise ValueError("Standalone narrative text has no positional dictionary")
        if len(bodies) != 1 or "field_index" in bodies[0]:
            raise ValueError("Standalone narrative requires its exact source body reference")
        header = validate_filing_header(row, header_row, selection)
        result = dict.fromkeys(COMMON_TEXT + EXTRA_TEXT + _TEXT_IDENTIFIERS)
        result.update(observation_fields(table, row, selection, "fec-filing-narrative/1"))
        result.update(
            declared_format_version=header["format_version"],
            filing_header_record_id=header_row["source_record_id"],
            filing_header_locator_json=_json(json.loads(header_row["source_locator_json"])),
            submission_conformance_status="not-qualified",
            mapping_status="mapped",
            mapping_reason_json=_json({"dictionary": "not-applicable-to-standalone-text"}),
            native_fields=[],
        )
        evidence = record_evidence(table, result["record_id"], row, selection.source_generation_pin)
        evidence += [
            {**e, "role": "filing_header"}
            for e in record_evidence(table, result["record_id"], header_row, selection.source_generation_pin)
        ]
        position, pointer, text, status = None, "/embedded_bodies/0", None, "source_body_reference"
    else:
        raise ValueError("Expected a source-owned TEXT record or standalone narrative text")
    if bodies:
        locator = json.loads(row["source_locator_json"])
        if "embedded_bodies" in locator and locator["embedded_bodies"] != bodies:
            raise ValueError("Narrative body differs from its native source locator")
        if locator.get("member") is None and bodies[0]["sha256"] != row["source_sha256"]:
            raise ValueError("Narrative body differs from its original source digest")
        text = read_body(bodies[0])
        if not isinstance(text, str):
            raise ValueError("Narrative reader must return source text")
        pointer, status = "/embedded_bodies/0", "resolved_source_body"
    if text == "":
        status = "source_empty"
    result.update(
        currency=None,
        amount_kind=None,
        source_namespace="fec-filing-narrative",
        text_record_kind=kind,
        text_fragments=[
            dict(
                field_position=position,
                source_column="metadata_json",
                source_pointer=pointer,
                text=text,
                text_status=status,
                body_reference_json=_json(bodies[0]) if bodies else None,
            )
        ],
    )
    return result, evidence


def map_filing_physical_text(row, selection):
    """Retain a source-owned physical line when filing syntax is uninterpreted.

    The source reader already separated lines and recorded their byte ranges.
    This does not parse header/record syntax or repair malformed framing. Blank
    lines and framing markers retain distinct source identities with their text.
    """
    native = json.loads(row["metadata_json"])
    fields = native.get("fields")
    locator = json.loads(row["source_locator_json"])
    source = native.get("source", {})
    if (
        native.get("kind") != "row"
        or not isinstance(fields, list)
        or len(fields) > 1
        or any(not isinstance(value, str) for value in fields)
        or source.get("sha256") != row["source_sha256"]
        or locator.get("member") is not None
        or any(
            key not in source or source[key] != locator.get(key)
            for key in ("sha256", "byte_offset", "byte_length", "encoding")
        )
    ):
        raise ValueError("Expected a pinned source-owned original physical filing line")
    table = "fec_filing_text_observations"
    result: dict = dict.fromkeys(COMMON_TEXT + EXTRA_TEXT + _TEXT_IDENTIFIERS)
    result.update(observation_fields(table, row, selection, "fec-filing-physical-text/1"))
    result.update(
        mapping_status="partial",
        mapping_reason_json=_json({"filing_syntax": "syntax-uninterpreted", "header_identity": "unresolved"}),
        submission_conformance_status="not-qualified",
        source_namespace="fec-filing-physical-text",
        text_record_kind="physical-line",
        native_fields=[
            dict(
                position=i,
                definition_label=None,
                definition_cell=None,
                presence="value",
                raw_value=value,
                body_reference_json=None,
            )
            for i, value in enumerate(fields)
        ],
        text_fragments=[
            dict(
                field_position=0 if fields else None,
                source_column="metadata_json",
                source_pointer="/fields/0" if fields else "/fields",
                text=fields[0] if fields else "",
                text_status="native_field" if fields else "source_empty",
                body_reference_json=None,
            )
        ],
    )
    return result, record_evidence(table, result["record_id"], row, selection.source_generation_pin)
