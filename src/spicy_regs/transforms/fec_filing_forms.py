@cache
def remaining_filing_mappings():
    """Finite mappings for the remaining witnessed native form/version pairs."""
    mappings = []
    for declared, version, form, pattern, pin, workbook, columns, table, grain in _LAYOUTS:
        names = _COLUMNS[columns].split()
        mappings.append(
            _mapping(
                form,
                pin.removeprefix("sha256:"),
                pattern,
                table,
                " ".join(names),
                " ".join(n for n in names if n in _AMOUNTS),
                " ".join(n for n in names if n in _DATES),
                (("financial_grain", grain), ("aggregation_status", "overlap-unqualified")),
                version=version,
                declared_versions=(declared,),
                workbook_sha256=workbook,
            )
        )
    existing = retained_filing_mappings()

    def source_mapping(version, form):
        choices = [m for m in existing if version in m.declared_versions and m.form == form]
        if len(choices) != 1:
            raise ValueError("Remaining filing mapping requires one reviewed source layout")
        return choices[0]

    for version, form, pattern in _SPECIAL:
        base = source_mapping(version, form)
        fields = replace(
            base.fields,
            key=base.fields.key.removesuffix("/1") + "-" + pattern + "/1",
            constants=base.fields.constants
            + (
                ("financial_grain", "special-account-receipt" if form == "SA" else "special-account-payment"),
                ("reported_account_form", pattern),
                ("aggregation_status", "overlap-unqualified"),
            ),
        )
        mappings.append(replace(base, fields=fields, record_pattern=pattern))

    base = source_mapping("8.1", "SA")
    fields = replace(
        base.fields,
        key="electronic-v8.1-SA3L/1",
        table="fec_bundled_contributions",
        text=tuple((n.replace("contributor_", "bundler_"), i) for n, i in base.fields.text),
        amounts=tuple(
            ("bundled_amount" if n == "amount" else "semiannual_bundled_amount", i) for n, i in base.fields.amounts
        ),
        constants=(
            ("financial_grain", "reported-bundler-period-aggregate"),
            ("aggregation_status", "overlap-unqualified"),
        ),
    )
    mappings.append(replace(base, fields=fields, record_pattern="SA3L"))
    return tuple(mappings)


def remaining_filing_mapping_for(declared_version, record_type):
    """Select exact retained header spelling and reviewed record type only."""
    if not isinstance(declared_version, str) or not isinstance(record_type, str):
        raise ValueError("Filing header version and record type must retain native text")
    choices = [
        m
        for m in remaining_filing_mappings()
        if declared_version in m.declared_versions and re.fullmatch(m.record_pattern, record_type)
    ]
    if len(choices) > 1:
        raise ValueError("Ambiguous remaining filing mapping")
    return choices[0] if choices else None


