@cache
def filing_cover_mappings():
    """Pinned report, statement and supplement layouts for witnessed headers.

    The v2 F3 dictionary contains an unexplained additional field among address
    columns. Its native observations retain every cell but expose no monetary or
    date interpretation; deleting that dictionary field is not authorized here.
    """
    mappings = []
    for declared, family, version, form, pattern, pin, workbook, count, cores, measures in _COVERS:
        names = [f"native_{i}" for i in range(count)]
        for i, name in _COVER_FIELD_SETS[cores]:
            names[i] = name
        amounts = []
        for i, _, _ in _COVER_MEASURE_SETS[measures]:
            names[i] = f"measure_{i}"
            amounts.append(names[i])
        mappings.append(
            _mapping(
                form,
                pin.removeprefix("sha256:"),
                pattern,
                "fec_filing_report_observations",
                " ".join(names),
                " ".join(amounts),
                " ".join(n for n in names if n in _COVER_DATES),
                family=family,
                version=version,
                declared_versions=(declared,),
                workbook_sha256=workbook,
            )
        )
    return tuple(mappings)


def filing_cover_mapping_for(declared_version, record_type):
    """Select a report record without inferring filing identity or amendments."""
    if not isinstance(declared_version, str) or not isinstance(record_type, str):
        raise ValueError("Filing header version and record type must retain native text")
    choices = [
        m
        for m in filing_cover_mappings()
        if declared_version in m.declared_versions and re.fullmatch(m.record_pattern, record_type)
    ]
    if len(choices) > 1:
        raise ValueError("Ambiguous cover filing mapping")
    return choices[0] if choices else None


def map_filing_cover(row, selection, mapping, *, layout, header_row):
    """Map a reported form observation, not an inferred filing version.

    Every native value, separated body reference and undefined position remains
    accessible. Monetary measures retain positional identities even when labels
    repeat; their report columns are not asserted to cover the same time span.
    """
    if mapping not in filing_cover_mappings():
        raise ValueError("Expected an explicitly reviewed cover/report mapping")
    typed, evidence = map_filing_financial(row, selection, mapping, layout=layout, header_row=header_row)
    result = {n: typed.get(n) for n in COMMON_TEXT + EXTRA_TEXT + _COVER_TEXT + ["source_cycle"]}
    for name in _COVER_DATES:
        for suffix in ("", "_raw"):
            result[name + suffix] = typed.get(name + suffix)
        result[name + "_status"] = typed.get(name + "_status", "not_defined_in_selected_layout")
    ambiguous = mapping.version == "v2" and mapping.form == "F3"
    result.update(
        source_namespace="fec-" + mapping.family + "-filing-report",
        definition_applicability_status="source-layout-ambiguous" if ambiguous else "caller-selected-not-conformance",
        report_record_role=(
            "supplement"
            if mapping.form in {"F1S", "F2S", "F3S", "F3Z"}
            else "account-summary"
            if mapping.form in {"SI", "SL", "Sch L"}
            else "reported-form"
        ),
        aggregation_status="overlap-unqualified",
    )
    if ambiguous:
        reasons = json.loads(result["mapping_reason_json"])
        reasons["definition_ambiguity"] = "v2-F3-unexplained-address-column-insertion"
        result.update(mapping_status="partial", mapping_reason_json=_json(reasons))
    native = json.loads(row["metadata_json"])
    result["native_fields"] = _native_fields(native, layout)
    spec = next(s for s in _COVERS if s[0] in mapping.declared_versions and s[5] == mapping.layout_pin)
    result["reported_measures"] = [
        dict(
            native_position=i,
            native_label=layout["fields"][i]["label"],
            definition_cell=layout["fields"][i]["cell"],
            raw_value=typed[f"measure_{i}_raw"],
            value=typed[f"measure_{i}"],
            value_status=typed[f"measure_{i}_status"],
            quantity_kind=quantity,
            measure_role=role,
            period_basis="native-report-column-not-harmonized",
        )
        for i, quantity, role in _COVER_MEASURE_SETS[spec[9]]
    ]
    return result, evidence


def _native_fields(native, layout):
    """Keep every source position, including separated bodies and undefined cells."""
    values = native["fields"]
    bodies = {b["field_index"]: b for b in native.get("embedded_bodies", [])}
    fields = []
    for i in range(max(native["field_count"], len(layout["fields"]))):
        definition = layout["fields"][i] if i < len(layout["fields"]) else {}
        fields.append(
            dict(
                position=i,
                definition_label=definition.get("label"),
                definition_cell=definition.get("cell"),
                presence="absent" if i >= native["field_count"] else "body" if i in bodies else "value",
                raw_value=values.get(str(i)),
                body_reference_json=_json(bodies[i]) if i in bodies else None,
            )
        )
    return fields


