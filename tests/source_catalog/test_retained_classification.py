"""Generated records share custody with original FEC responses, but not source use."""

import hashlib
import json

import pytest

from spicy_regs.source_catalog.importer import build
from spicy_regs.source_catalog.raw_archive import classify_retained_objects, retained_classification_candidates
from spicy_regs.source_catalog.raw_classification import generated_content_metadata
from spicy_regs.source_catalog.storage import connect

DIGEST = "sha256:" + "a" * 64
PAGE = {
    "accepted": True, "discoveredRecords": [], "evidenceBlobRef": DIGEST,
    "evidenceMediaType": "application/json", "pageIndex": 0, "recordsIncluded": True,
    "requestKey": "https://api.open.fec.gov/v1/candidates/", "responseDigest": DIGEST,
    "sourceCursor": None, "terminal": True, "traversalIndex": 0, "windowIndex": 0, "windowPageIndex": 0,
}
LEDGER = {"evidenceBlobRef": DIGEST, "failure": None, "observationRef": {}, "sourceRecordId": "candidate-1"}
RECORD = {"fieldDiagnostics": [], "record": {"name": "retained observed value"}, "schemaDigest": DIGEST,
          "schemaName": "fec-candidate-record", "schemaVersion": "1.0", "scopeId": "candidates",
          "sourceRecordId": "candidate-1"}


@pytest.mark.parametrize(("value", "kind", "role"), [
    (PAGE, "acquisition-page", "acquisition-receipt"),
    (LEDGER, "acquisition-ledger", "acquisition-receipt"),
    (RECORD, "source-native-record", "processing-evidence"),
])
def test_maintained_shapes_and_homogeneous_jsonl(value, kind, role):
    for body in (json.dumps(value).encode(), (json.dumps(value) + "\n" + json.dumps(value) + "\n").encode()):
        result = generated_content_metadata(body)
        assert result is not None
        assert result["content_kind"] == kind
        assert result["role"] == role
    invalid = dict(value, evidenceBlobRef=5) if "evidenceBlobRef" in value else dict(value, schemaDigest=False)
    invalid_result = generated_content_metadata(json.dumps(invalid).encode())
    assert invalid_result is not None and invalid_result["classification"] == "uncertain"


def retained_fixture(tmp_path):
    from spicy_docs.storage.raw_archive import CentralRawArchiveStore

    root = tmp_path / "raw"
    store = CentralRawArchiveStore(root)
    files, hashes = [], {}
    samples = {
        "page": json.dumps(PAGE).encode(), "ledger": json.dumps(LEDGER).encode(),
        "normalized": json.dumps(RECORD).encode(),
        "publisher-api": b'{"api_version":"1.0","pagination":{"page":1,"pages":1},"results":[{"candidate_id":"H2AK01158"}]}',
        "publisher-filing": b'HDR\x1cFEC\x1c8.1\x1csource\nF1\x1cC00000001\n',
        "uncertain": json.dumps(dict(PAGE, accepted="yes")).encode(),
    }
    for name, body in samples.items():
        sha = hashlib.sha256(body).hexdigest()
        hashes[name] = "sha256:" + sha
        store.put_blob(sha, len(body), [body])
        member = "blobs/sha256/" + sha
        witness = {"sha256": sha, "bytes": len(body), "name": name,
                   "original_location": f"/old/source-evidence/{'b' * 64}/{member}",
                   "receipt_context": {"family": "fec-query", "artifact": "sha256:" + "b" * 64,
                                       "declared_role": "evidence", "member": member}}
        # The other dataset is deliberately imported before the producer witness.
        files.append(dict(witness, name=name + "-alias", dataset_id="family:fec-source-catalog",
                          original_location="/other/source.bin", receipt_context={}))
        files.append(witness)
        files.append(dict(witness, name=name + "-receipt", role="acquisition-receipt",
                          original_location="/original/receipt.json", receipt_context={}))
    # A valid-looking shape alone, under ordinary original-response provenance,
    # cannot establish that the bytes were generated by our local producer.
    body = json.dumps(dict(PAGE, pageIndex=3)).encode()
    sha = hashlib.sha256(body).hexdigest()
    store.put_blob(sha, len(body), [body])
    files.append({"sha256": sha, "bytes": len(body), "name": "shape-only",
                  "dataset_id": "publisher:ordinary", "original_location": "https://example.test/source"})
    store.record_receipt(files=files, receipt={"status": "captured"})
    config = tmp_path / "registry.json"
    config.write_text("{}")
    index = tmp_path / "index.sqlite"
    build(root, index, config=config)
    return root, index, hashes


def test_classification_propagates_kind_preserves_original_facts_and_source_aliases(tmp_path):
    root, index, hashes = retained_fixture(tmp_path)
    with connect(index, scope="all") as db:
        rows = {r["name"]: r for r in db.execute("SELECT * FROM main.files")}
        for name in ("page", "ledger", "normalized"):
            expected = "receipt-only" if name in {"page", "ledger"} else "supporting-evidence"
            for alias in (name, name + "-alias"):
                row = rows[alias]
                assert row["status"] == expected
                facts = json.loads(row["data"])
                assert facts["mapping"]["content_metadata"]["raw_sha256"] == hashes[name]
                assert facts["mapping"]["content_metadata"]["producer_evidence"]["receipt_context"]["family"] == "fec-query"
                if alias.endswith("-alias"):
                    assert row["collection_id"] == "family:fec-source-catalog"
                    assert facts["receipt_context"] == {}
                    assert facts["mapping"]["role"] == "original-response"
            assert rows[name + "-receipt"]["status"] == "receipt-only"
        for name in ("publisher-api", "publisher-filing"):
            assert rows[name]["status"] == rows[name + "-alias"]["status"] == "held"
            assert rows[name + "-receipt"]["status"] == "receipt-only"
            assert json.loads(rows[name]["data"])["mapping"]["content_metadata"]["classification"] == "source-original"
        assert rows["shape-only"]["status"] == "held"
        assert rows["uncertain"]["status"] == "unclassified-source"
        assert json.loads(rows["uncertain"]["data"])["mapping"]["content_metadata"]["classification"] == "uncertain"
        before = [tuple(r) for r in db.execute("SELECT * FROM main.files ORDER BY id")]
        summary = classify_retained_objects(db, root, retained_classification_candidates(db))
        assert summary.get("annotated_aliases", 0) == 0
        assert [tuple(r) for r in db.execute("SELECT * FROM main.files ORDER BY id")] == before


def test_classification_rolls_back_all_prior_updates_when_a_later_identity_fails(tmp_path):
    root, index, hashes = retained_fixture(tmp_path)
    with connect(index, scope="all") as db:
        # Recreate an unclassified candidate without changing any raw byte.
        for row in list(db.execute("SELECT id,data FROM main.files")):
            facts = json.loads(row["data"])
            facts["mapping"].pop("content_metadata", None)
            db.execute("UPDATE main.files SET data=? WHERE id=?", (json.dumps(facts), row["id"]))
        before = [tuple(r) for r in db.execute("SELECT * FROM main.files ORDER BY id")]
        with pytest.raises(ValueError, match="qualified original"):
            classify_retained_objects(db, root, [hashes["page"], "invalid-digest"])
        assert [tuple(r) for r in db.execute("SELECT * FROM main.files ORDER BY id")] == before


@pytest.mark.parametrize(("sample", "expected"), [
    ("publisher-filing", "held"), ("page", "receipt-only"), ("normalized", "supporting-evidence"),
])
def test_newly_resolved_uncertainty_uses_current_content_kind(tmp_path, sample, expected):
    root, index, hashes = retained_fixture(tmp_path)
    with connect(index, scope="all") as db:
        db.execute("UPDATE main.files SET status='unclassified-source' WHERE sha256=? AND name NOT LIKE '%-receipt'",
                   (hashes[sample],))
        # Independent source refusal is stronger than the parser's content kind.
        db.execute("UPDATE main.files SET status='refused-source' WHERE name=?", (sample + "-receipt",))
        classify_retained_objects(db, root, [hashes[sample]])
        assert db.execute("SELECT status FROM main.files WHERE name=?", (sample,)).fetchone()[0] == expected
        assert db.execute("SELECT status FROM main.files WHERE name=?", (sample + "-receipt",)).fetchone()[0] == "refused-source"
        before = [tuple(r) for r in db.execute("SELECT * FROM main.files ORDER BY id")]
        classify_retained_objects(db, root, [hashes[sample]])
        assert [tuple(r) for r in db.execute("SELECT * FROM main.files ORDER BY id")] == before


def test_stronger_reviewed_original_causes_explicit_conflict(tmp_path):
    root, index, hashes = retained_fixture(tmp_path)
    with connect(index, scope="all") as db:
        row = db.execute("SELECT id,data FROM main.files WHERE name='normalized-alias'").fetchone()
        facts = json.loads(row["data"])
        facts["content_review"] = {"decision": {"classification": "source-original", "role": "original-response",
                                              "non_publisher_source": False}}
        db.execute("UPDATE main.files SET data=? WHERE id=?", (json.dumps(facts), row["id"]))
        before = [tuple(r) for r in db.execute("SELECT * FROM main.files ORDER BY id")]
        with pytest.raises(ValueError, match="conflicts with a reviewed source original"):
            classify_retained_objects(db, root, [hashes["normalized"]])
        assert [tuple(r) for r in db.execute("SELECT * FROM main.files ORDER BY id")] == before


def test_artifact_identity_is_generated_metadata_without_member_admission():
    from rulespec_artifacts import Producer, stamp_root

    value = stamp_root({
        "format": "spicy-artifact", "formatVersion": "1.0", "kind": "spicyregs-source-native-release",
        "inputs": [], "spec": {}, "memberManifests": [],
        "counts": {"manifestCount": 0, "memberCount": 0, "totalMemberByteSize": 0, "totalRecordCount": 0},
        "producer": Producer("spicy-docs", "git+https://example.test/repo@" + "b" * 40,
                             "urn:test:verifier", "2.0", "git+https://example.test/repo@" + "b" * 40).as_dict(),
    })
    result = generated_content_metadata(json.dumps(value).encode())
    assert result is not None
    assert result["content_kind"] == "artifact-manifest"
    assert result["classification"] == "derived-support"
    changed = dict(value, spec={"changed": True})
    changed_result = generated_content_metadata(json.dumps(changed).encode())
    assert changed_result is not None and changed_result["classification"] == "uncertain"


@pytest.mark.parametrize(("classification", "role", "expected"), [
    ("source-original", "original-response", "held"),
    ("derived-support", "processing-evidence", "supporting-evidence"),
    ("acquisition-receipt", "acquisition-receipt", "receipt-only"),
    ("source-error", "failed-response", "refused-source"),
    ("uncertain", "unknown", "unclassified-source"),
])
def test_exact_byte_review_survives_rebuild_without_rewriting_capture_facts(
        tmp_path, monkeypatch, classification, role, expected):
    from spicy_regs.source_catalog import raw_classification

    root, index, hashes = retained_fixture(tmp_path)
    with connect(index, scope="all") as db:
        original = db.execute("SELECT * FROM files WHERE name='uncertain'").fetchone()
        before = json.loads(original["data"])
        result = {"outcome": "uncertain" if classification == "uncertain" else "ok",
                  "classification": classification, "content_kind": "reviewed-test",
                  "role": role, "scope": {"basis": "Local exact-byte inspection", "limits": ["No completeness claim"]},
                  "evidence": [{"locator": "/", "rule": "test-byte-review", "target": "role", "value": role}]}
        reviews = tmp_path / "reviews.json"
        reviews.write_text(json.dumps({"version": 1, "description": "test", "objects": {
            hashes["uncertain"]: {"bytes": original["bytes"], "result": result},
        }}))
        monkeypatch.setattr(raw_classification, "RETAINED_REVIEWS", reviews)
        # A reviewed object may exceed the normal parser's limit. Verification
        # still reads every byte, while unknown objects keep the existing bound.
        counts = classify_retained_objects(db, root, [hashes["uncertain"]], max_bytes=1)
        assert counts["reviewed_objects"] == 1
        after = db.execute("SELECT status,data FROM files WHERE name='uncertain'").fetchone()
        assert after["status"] == expected
        assert db.execute("SELECT status FROM files WHERE name='uncertain-receipt'").fetchone()[0] == "receipt-only"
        assert json.loads(after["data"])["receipt_context"] == before["receipt_context"]
        assert json.loads(after["data"])["mapping"]["http_status"] == before["mapping"]["http_status"]
        prior_review = json.loads(after["data"])["mapping"]["content_metadata"]["scope"]["review_sha256"]
        corrected = {"locator": "/field", "rule": "corrected-locator", "target": "role", "value": role}
        result["evidence"] = [corrected]
        reviews.write_text(json.dumps({"version": 1, "description": "test", "objects": {
            hashes["uncertain"]: {"bytes": original["bytes"], "result": result},
        }}))
        classify_retained_objects(db, root, [hashes["uncertain"]])
        updated = json.loads(db.execute("SELECT data FROM files WHERE name='uncertain'").fetchone()[0])["mapping"]
        assert updated["content_metadata"]["scope"]["review_sha256"] != prior_review
        assert dict(corrected, origin="content") in updated["evidence"]
    rebuilt = tmp_path / "rebuilt.sqlite"
    build(root, rebuilt, config=tmp_path / "registry.json")
    with connect(rebuilt, scope="all") as db:
        assert db.execute("SELECT status FROM files WHERE name='uncertain'").fetchone()[0] == expected
        assert db.execute("SELECT status FROM files WHERE name='shape-only'").fetchone()[0] == "held"


def test_review_cannot_bypass_original_byte_verification(tmp_path, monkeypatch):
    from spicy_regs.source_catalog import raw_archive

    root, index, hashes = retained_fixture(tmp_path)
    with connect(index, scope="all") as db:
        original = db.execute("SELECT * FROM files WHERE name='uncertain'").fetchone()
        monkeypatch.setattr(raw_archive, "retained_content_reviews", lambda: {
            hashes["uncertain"]: {"bytes": original["bytes"], "result": {}},
        })
        path = root / json.loads(original["data"])["object"]
        body = path.read_bytes()
        path.write_bytes(bytes([body[0] ^ 1]) + body[1:])
        before = list(db.execute("SELECT id,status,data FROM files ORDER BY id"))
        with pytest.raises(ValueError, match="Reviewed original changed"):
            classify_retained_objects(db, root, [hashes["uncertain"]])
        assert list(db.execute("SELECT id,status,data FROM files ORDER BY id")) == before
